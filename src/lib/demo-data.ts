export function demoForRole(role: Role): WorkspaceData {
  return {
    ...demoData,
    products: role === "driver" ? [] : demoData.products,
    retailSales:
      role === "sme" || role === "driver"
        ? []
        : role === "branch"
          ? demoData.retailSales.filter((s) => s.branchId === "b1")
          : demoData.retailSales,
    orders:
      role === "sme"
        ? demoData.orders.filter((o) => o.initials === "MT")
        : role === "branch"
          ? []
          : role === "driver"
            ? demoData.orders.filter((o) => o.status === "Shipping")
            : demoData.orders,
    accounts: role === "hq" ? demoData.accounts : [],
    branches:
      role === "branch"
        ? demoData.branches.filter((b) => b.id === "b1")
        : demoData.branches,
  };
}
